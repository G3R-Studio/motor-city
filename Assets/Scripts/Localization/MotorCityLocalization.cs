        private static string language = Russian;

        public static string LanguageCode =>
            language;

        public static void SetLanguage(
            string code)
        {
            language =
                NormalizeLanguage(
                    code);
        }

        public static string Text(
            string key)
        {
            if (string.IsNullOrWhiteSpace(
                    key))
            {
                return string.Empty;
            }

            if (MotorCityInput.PreferTouchPrompts &&
                TouchPromptOverrides.TryGetValue(
                    key,
                    out LocalizedEntry touchEntry))
            {
                return language == English
                    ? touchEntry.English
                    : touchEntry.Russian;
            }

            if (!Entries.TryGetValue(
                    key,
                    out LocalizedEntry entry))
            {
                return key;
            }

            return language == English
                ? entry.English
                : entry.Russian;
        }

        public static string Format(
            string key,
            params object[] args)
        {
            string template =
                Text(
                    key);

            if (args == null ||
                args.Length == 0)
            {
                return template;
            }

            return string.Format(
                CultureInfo.CurrentCulture,
                template,
                args);
        }

        private static string NormalizeLanguage(
            string code)
        {
            if (string.IsNullOrWhiteSpace(
                    code))
            {
                return Russian;
            }

            return code.StartsWith(
                    English,
                    StringComparison.OrdinalIgnoreCase)
                ? English
                : Russian;
        }

        private static LocalizedEntry E(
            string russian,
            string english)
        {
            return
                new LocalizedEntry(
                    russian,
                    english);
        }

        private readonly struct LocalizedEntry
        {
            public readonly string Russian;
            public readonly string English;

            public LocalizedEntry(
                string russian,
                string english)
            {
                Russian =
                    russian ?? string.Empty;

                English =
                    english ?? russian ?? string.Empty;
            }
        }
